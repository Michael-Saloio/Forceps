    private void createStaffAccount(String role, String firstName, String lastName, String phone,
            String email, String hireDateText, String accountStatus) {
        if ("Doctor".equals(role)
                && (licenseField.getText().trim().isEmpty() || specialtyField.getText().trim().isEmpty())) {
            JOptionPane.showMessageDialog(this, "Doctor license number and specialty are required.");
            return;
        }
        if ("Nurse".equals(role) && licenseField.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nurse license number is required.");
            return;
        }

        try {
            Date hireDate = Date.valueOf(LocalDate.parse(hireDateText, DateTimeFormatter.ofPattern("dd-MM-yyyy")));
            char[] passwordChars = passwordField.getPassword();
            String passwordHash = hashPassword(new String(passwordChars));
            java.util.Arrays.fill(passwordChars, '\0');

            String procedure;
            int parameterCount;
            if ("Doctor".equals(role)) { procedure = "add_doctor"; parameterCount = 15; }
            else if ("Nurse".equals(role)) { procedure = "add_nurse"; parameterCount = 14; }
            else if ("Receptionist".equals(role)) { procedure = "add_receptionist"; parameterCount = 13; }
            else if ("Remote Worker".equals(role)) { procedure = "add_remote_worker"; parameterCount = 13; }
            else { procedure = "add_system_admin"; parameterCount = 13; }

            String placeholders = String.join(",", java.util.Collections.nCopies(parameterCount, "?"));
            String call = "{CALL " + procedure + "(" + placeholders + ")}";
            try (Connection connection = DatabaseConnection.getConnection();
                    CallableStatement statement = connection.prepareCall(call)) {
                statement.setNull(1, Types.BIGINT); // generated staff ID
                statement.setNull(2, Types.BIGINT); // generated account ID
                if (createdByStaffId > 0) statement.setLong(3, createdByStaffId);
                else statement.setNull(3, Types.BIGINT);
                statement.setString(4, firstName);
                statement.setString(5, lastName);
                if (phone.isEmpty()) statement.setNull(6, Types.VARCHAR);
                else statement.setString(6, phone);
                statement.setString(7, email);
                setOptionalString(statement, 8, departmentField.getText());
                statement.setDate(9, hireDate);
                statement.setNull(10, Types.DATE);

                if ("Doctor".equals(role)) {
                    statement.setString(11, licenseField.getText().trim());
                    statement.setString(12, specialtyField.getText().trim());
                    statement.setString(13, usernameField.getText().trim());
                    statement.setString(14, passwordHash);
                    statement.setString(15, accountStatus.toUpperCase(java.util.Locale.ROOT));
                } else if ("Nurse".equals(role)) {
                    statement.setString(11, licenseField.getText().trim());
                    statement.setString(12, usernameField.getText().trim());
                    statement.setString(13, passwordHash);
                    statement.setString(14, accountStatus.toUpperCase(java.util.Locale.ROOT));
                } else {
                    statement.setString(11, usernameField.getText().trim());
                    statement.setString(12, passwordHash);
                    statement.setString(13, accountStatus.toUpperCase(java.util.Locale.ROOT));
                }
                statement.execute();

                long newStaffId;
                long newAccountId;
                try (PreparedStatement query = connection.prepareStatement(
                        "SELECT s.staff_id, ua.account_id FROM Staff s JOIN User_account ua ON ua.staff_id=s.staff_id WHERE s.email=?")) {
                    query.setString(1, email);
                    try (ResultSet result = query.executeQuery()) {
                        if (!result.next()) throw new SQLException("The account was created but could not be retrieved.");
                        newStaffId = result.getLong("staff_id");
                        newAccountId = result.getLong("account_id");
                    }
                }
                JOptionPane.showMessageDialog(this, role + " account created.\nStaff ID: " + newStaffId
                        + "\nAccount ID: " + newAccountId + "\nShare the temporary password securely.");
                passwordField.setText("");
                dispose();
            }
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, "Enter the hire date as DD-MM-YYYY.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Unable to create staff account: " + ex.getMessage(),
                    "Database error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void setOptionalString(CallableStatement statement, int index, String value) throws SQLException {
        String text = value == null ? "" : value.trim();
        if (text.isEmpty()) statement.setNull(index, Types.VARCHAR);
        else statement.setString(index, text);
    }

    private String hashPassword(String password) {
        try {
            byte[] hash = MessageDigest.getInstance("SHA-256").digest(password.getBytes(StandardCharsets.UTF_8));
            StringBuilder result = new StringBuilder(hash.length * 2);
            for (byte value : hash) result.append(String.format("%02x", value));
            return result.toString();
        } catch (java.security.NoSuchAlgorithmException ex) {
            throw new IllegalStateException("SHA-256 is unavailable.", ex);
        }
    }
